use super::*;
use quota_core::provider::{CredentialHandle, FetchAttempt, HandlesError, UsageProvider};
use sha2::Digest as _;
use std::path::PathBuf;

const AT: i64 = 1793600000000;
struct VectorPoll(&'static str, &'static str);
#[async_trait::async_trait]
impl UsageProvider for VectorPoll {
    fn name(&self) -> &str {
        self.0
    }
    fn handles(&self) -> Result<Vec<CredentialHandle>, HandlesError> {
        Ok(vec![CredentialHandle::scoped(self.1, "oauth")])
    }
    async fn fetch_handle(&self, _: &CredentialHandle) -> FetchAttempt {
        FetchAttempt::from_provider_usage(Ok(serde_json::from_value(json!({
            "provider":self.0,"account":"synthetic-account","source":"oauth",
            "usage":{"primary":{"usedPercent":10,"windowMinutes":300},
                "secondary":{"usedPercent":30,"windowMinutes":10080}}
        }))
        .unwrap()))
        .with_value_observed_at("2026-09-26T03:39:59Z".parse().unwrap())
    }
}

const README: &str = "# usage.observe v1 wire vectors\n\nSynthetic identities only. Requests and replies are the JSON frame body bytes, without a trailing newline, produced and decoded by insula's real usage.observe handler. Each pair starts from a successful poll with a 300-minute primary and 10080-minute secondary window. Each request includes an unknown credential to pin ignored-row encoding. The frame sample includes limit_reached: true; that flag is deliberately ignored.\n\nWriters forward Claude's anthropic-ratelimit-unified-* headers. The Codex header allowlist is every x-codex-* header except x-codex-turn-state, plus x-*-primary-*, x-*-secondary-* and x-*-limit-name. Insula parses only the default x-codex-* family and ignores the rest. The broca-codex-headers request includes a non-default family that cannot override the default weekly window.\n\nPairs: broca-codex-headers, broca-codex-frame, claustrum-vouched-claude. Every row requires credentialId; optional account must match the selected slot's resolved vault account id. Only reserved:claustrum may vouch, and every Claustrum row must include vouched principal and credentialId: the relay attests that it admitted that enrolled principal to report this credential. The vouched principal is diagnostic only; vouched.credentialId must equal the row's credentialId. The result is wrapped in result by the transport.\n\nSHA256SUMS covers every other file, in shasum -a 256 format. Verify with shasum -a 256 -c SHA256SUMS. Regenerate with INSULA_WRITE_VECTORS=1 cargo test -p quota-module --bin ck-insula committed_usage_observe_vectors_match. The drift test compares generated bytes and checksums and refuses unexpected files.\n";

async fn generated_files() -> Vec<(String, Vec<u8>)> {
    let mut files = Vec::new();
    for (name, writer, mut row) in [
        (
            "broca-codex-headers",
            "broca",
            json!({"provider":"codex","credentialId":"chatgpt:openai:synthetic","observedAtMs":AT,
            "headers":{"x-codex-primary-used-percent":"100","x-codex-primary-window-minutes":"10080","x-codex-primary-reset-at":"1793774135",
                "x-codex-secondary-used-percent":"0","x-codex-secondary-window-minutes":"0","x-codex-secondary-reset-at":"",
                "x-codex-secondary-primary-used-percent":"12","x-codex-secondary-limit-name":"codex_secondary"}}),
        ),
        (
            "broca-codex-frame",
            "broca",
            json!({"provider":"codex","credentialId":"chatgpt:openai:synthetic","observedAtMs":AT,
            "frame":{"type":"codex.rate_limits","rate_limits":{"allowed":false,"limit_reached":true,
                "primary":{"used_percent":100,"window_minutes":10080,"reset_at":1793774164},"secondary":null},
                "additional_rate_limits":null,"credits":{"has_credits":true,"unlimited":false,"balance":"1234.5000000000"}}}),
        ),
        (
            "claustrum-vouched-claude",
            "claustrum",
            json!({"provider":"claude","credentialId":"oauth:claude:synthetic","account":"synthetic-account","observedAtMs":AT,
            "headers":{"anthropic-ratelimit-unified-5h-utilization":"0.41","anthropic-ratelimit-unified-5h-reset":"1793606400"},
            "vouched":{"principal":"enrolled:synthetic","credentialId":"oauth:claude:synthetic"}}),
        ),
    ] {
        let registry = Arc::new(Registry::new(vec![
            Box::new(VectorPoll("codex", "chatgpt:openai:synthetic")),
            Box::new(VectorPoll("claude", "oauth:claude:synthetic")),
        ]));
        registry.refresh_tick(&CancellationToken::new()).await;
        let mut unknown = row.clone();
        unknown["credentialId"] = json!("unknown-credential");
        if writer == "claustrum" {
            unknown["vouched"]["credentialId"] = json!("unknown-credential");
        }
        let body = serde_json::to_vec(
            &json!({"method":"usage.observe","params":{"observations":[row.take(),unknown]}}),
        )
        .unwrap();
        let mut wire = Wire::with_registry(false, 64 * 1024, registry).await;
        bind_writer(&mut wire, json!({"kind":"reserved","module_id":writer}), 1).await;
        wire.send(
            Frame::build(FrameType::Request, control_flags(), 5, 1, 401, body.clone()).unwrap(),
        )
        .await;
        let response = wire.recv().await;
        let result: Value = serde_json::from_slice(&response.body).unwrap();
        assert_eq!(result["result"]["accepted"], 1, "{name}: {result}");
        assert_eq!(
            result["result"]["ignored"][0]["reason"],
            "unknown_credential"
        );
        files.push((format!("{name}-request.json"), body));
        files.push((format!("{name}-reply.json"), response.body));
        wire.stop().await;
        wire.finish().await;
    }
    files.push(("README.md".into(), README.as_bytes().to_vec()));
    let sums = files
        .iter()
        .map(|(name, bytes)| format!("{:x}  {name}\n", sha2::Sha256::digest(bytes)))
        .collect::<String>();
    files.push(("SHA256SUMS".into(), sums.into_bytes()));
    files
}

#[tokio::test]
async fn committed_usage_observe_vectors_match() {
    let directory =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../test-vectors/usage-observe-v1");
    let files = generated_files().await;
    if std::env::var_os("INSULA_WRITE_VECTORS").as_deref() == Some(std::ffi::OsStr::new("1")) {
        std::fs::create_dir_all(&directory).unwrap();
        for (name, bytes) in &files {
            std::fs::write(directory.join(name), bytes).unwrap();
        }
    }
    let mut differences = Vec::new();
    for (name, bytes) in &files {
        if std::fs::read(directory.join(name)).ok().as_ref() != Some(bytes) {
            differences.push(name.clone());
        }
    }
    if let Ok(entries) = std::fs::read_dir(&directory) {
        for entry in entries {
            let name = entry.unwrap().file_name().to_string_lossy().into_owned();
            if !files.iter().any(|(expected, _)| *expected == name) {
                differences.push(name);
            }
        }
    }
    assert!(
        differences.is_empty(),
        "usage observation vectors differ: {differences:?}"
    );
}
